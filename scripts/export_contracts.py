import json
from pathlib import Path
from typing import cast

from defect_lens.api import create_app
from defect_lens.config import Settings
from defect_lens.contracts import Inspection, Job, ReadyState, Review, ReviewCreate
from defect_lens.routes import JobList, ModelMetadata, ReviewList

Json = dict[str, object]


def ts_type(schema: Json) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).split("/")[-1]
    if "anyOf" in schema:
        return " | ".join(ts_type(s) for s in cast(list[Json], schema["anyOf"]))
    if "enum" in schema:
        return " | ".join(json.dumps(s) for s in cast(list[object], schema["enum"]))
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{ts_type(cast(Json, schema['items']))}>"
    if kind == "object":
        return f"Record<string, {ts_type(cast(Json, schema.get('additionalProperties', {})))}>"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(kind), "unknown")


def export(root: Path) -> None:
    definitions: dict[str, Json] = {}
    for model in [
        ReadyState,
        Job,
        Inspection,
        Review,
        ReviewCreate,
        JobList,
        ReviewList,
        ModelMetadata,
    ]:
        schema = cast(Json, model.model_json_schema())
        definitions.update(cast(dict[str, Json], schema.pop("$defs", {})))
        definitions[model.__name__] = schema
    lines = ["// Generated by scripts/export_contracts.py; edit Python contracts first."]
    for name, schema in sorted(definitions.items()):
        lines.append(f"export interface {name} {{")
        for field, details in cast(dict[str, Json], schema["properties"]).items():
            lines.append(f"  {field}: {ts_type(details)};")
        lines.append("}")
    (root / "web/src/types.ts").write_text("\n".join(lines) + "\n")
    schema = create_app(Settings(root)).openapi()
    (root / "docs/api/openapi.json").write_text(json.dumps(schema, indent=2) + "\n")


if __name__ == "__main__":
    export(Path.cwd())
