from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

Decision = Literal["pass", "review", "fail"]
Method = Literal["difference", "resnet18_patch"]
DataMode = Literal["procedural", "owned_capture"]
JobStatus = Literal["queued", "running", "succeeded", "failed"]
ModelStatus = Literal["unprepared", "loading", "ready", "busy", "degraded"]


class Contract(BaseModel):
    model_config = ConfigDict(extra="forbid", allow_inf_nan=False)


class ReadyState(Contract):
    status: ModelStatus = "unprepared"
    model_revision: str | None = None
    method: Method | None = None
    data_mode: DataMode | None = None
    worker_alive: bool = False
    reason: str | None = "No prepared model selected"


class JobError(Contract):
    code: str
    message: str
    retryable: bool = False
    request_id: str = ""
    details: dict[str, str | int | float | None] = Field(default_factory=dict)


class SampleRecord(Contract):
    id: str
    image_path: str
    image_sha256: str
    specimen_id: str
    session_id: str
    split: Literal["train", "validation", "test"]
    label: Literal["good", "defect", "ambiguous"]
    defect_kind: Literal["none", "missing_fastener", "surface_mark", "quality"]
    mask_path: str | None = None
    mask_sha256: str | None = None
    lighting: Literal["normal", "dim", "bright"] = "normal"
    blur: Literal["none", "mild", "strong"] = "none"
    source: Literal["owned_procedural", "owned_photo"] = "owned_procedural"
    rights_note: str = "Original procedural image generated by Defect Lens; MIT"
    captured_at: str | None = None


class DatasetManifest(Contract):
    schema_version: int = 1
    mode: DataMode = "procedural"
    generator_revision: str | None = "tabletop-v1"
    seed: int | None = None
    samples: list[SampleRecord]


class InputMetadata(Contract):
    raw_sha256: str
    width: int
    height: int
    aspect_ratio: float
    image_format: str = "PNG"


class AcceptedInput(Contract):
    normalized_path: Path
    metadata: InputMetadata


class UploadForm(Contract):
    model_revision: str = Field(pattern=r"^[0-9a-f]{64}$")
    data_mode: DataMode


class Job(Contract):
    id: str
    status: JobStatus
    model_revision: str
    data_mode: DataMode
    created_at: str
    started_at: str | None = None
    finished_at: str | None = None
    inspection_id: str | None = None
    error: JobError | None = None


class Region(Contract):
    x: int
    y: int
    width: int
    height: int
    peak_score: float


class ReviewCreate(Contract):
    decision: Decision
    note: str = Field(max_length=1000)
    operator_alias: str = Field(min_length=1, max_length=80)
    expected_version: int = Field(ge=0)


class Review(Contract):
    id: str
    inspection_id: str
    version: int
    decision: Decision
    note: str
    operator_alias: str
    created_at: str
    model_revision: str


class Inspection(Contract):
    id: str
    job_id: str
    model_revision: str
    data_mode: DataMode
    original_decision: Decision
    score: float | None
    reasons: list[str]
    aligned_image_url: str | None
    heatmap_url: str | None
    normalized_image_url: str
    regions: list[Region]
    latest_review: Review | None = None


class StoredResult(Contract):
    decision: Decision
    score: float | None
    reasons: list[str]
    artifacts: dict[str, str]
    artifact_bytes: int
    regions: list[Region]
